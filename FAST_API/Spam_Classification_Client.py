# ============================================================
# FastAPI 스팸 판별 클라이언트
#
# 1. 사용자에게 분석할 문장을 입력받음
# 2. FastAPI 서버로 POST 요청
# 3. 서버의 스팸 판별 결과를 받아와서 콘솔에 출력
# ============================================================
import requests

# ------------------------------------------------------------
# 1. FastAPI 서버 주소
# ------------------------------------------------------------
SERVER_URL = "http://192.168.0.174:8000/spam"

# ------------------------------------------------------------
# 2. 사용자 입력
# ------------------------------------------------------------
text = input("분석할 문장을 입력하세요 : ")

# ------------------------------------------------------------
# 3. 서버에 전달할 JSON 데이터
# ------------------------------------------------------------
data = {
    "text": text
}

# ------------------------------------------------------------
# 4. FastAPI 서버에 POST 요청
# ------------------------------------------------------------
response = requests.post(
    SERVER_URL,
    json=data
)

# ------------------------------------------------------------
# 5. 서버 응답 처리
# ------------------------------------------------------------
if response.status_code == 200:

    result = response.json()

    print("\n===== 분석 결과 =====")
    print("입력 문장 :", result["text"])
    print("스팸 여부 :", result["spam"])
    print("신뢰도    :", result["confidence"])

else:
    print("서버 오류 :", response.status_code)
    print(response.text)