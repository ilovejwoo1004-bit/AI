# =============================================
# TCP/IP 클라이언트 예제
# =============================================
# 사용자가 입력한 메세지를 서버로 전송하고,
# 서버의 응답을 받아 출력하는 클라이언트 기능

import socket  # 네트워크 통신 모듈

#------------------------------------
# 1. 서버 접속 정보 설정
#------------------------------------
HOST = '192.168.0.174'  # 서버의 ip 주소
PORT = 9998

#------------------------------------
# 2. 소켓 객체 생성
#------------------------------------
# IPv4(socket.AF_INET) + TCP 프로토콜(socket.SOCK_STREAM) 사용
client_socket = socket.socket(socket.AF_INET, socket.SOCK_STREAM)

#------------------------------------
# 3. 서버에 연결 시도
#------------------------------------
client_socket.connect((HOST, PORT))
print(f"서버 ({HOST}:{PORT})에 연결되었습니다.")
print("메세지를 입력하세요. (종료하려면 'exit' 입력) \n")

#------------------------------------
# 4. 메세지 송수신 루프
#------------------------------------
while True:
    # 사용자 입력 대기
    message = input("보낼 메세지: ")

    # exit 입력 시, 종료
    if message.lower() == "exit":
        client_socket.sendall(message.encode())
        break

    # 서버로 메세지 전송
    client_socket.sendall(message.encode())

    # 서버로부터 응답 수신
    data = client_socket.recv(1024).decode()
    print(f"서버 응답: {data}\n")

#------------------------------------
# 5. 소켓 종료
#------------------------------------
client_socket.close()
print("클라이언트 종료 완료")



